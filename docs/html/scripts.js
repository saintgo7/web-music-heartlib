/**
 * Common JavaScript for Dev Log Visualization
 * Shared functions across all pages
 */

// ==========================================
// Dark Mode Management
// ==========================================

function toggleDarkMode() {
    document.body.classList.toggle('dark-mode');
    const isDark = document.body.classList.contains('dark-mode');

    const icon = document.getElementById('darkModeIcon');
    const label = document.getElementById('darkModeLabel');

    if (icon) icon.textContent = isDark ? '☀️' : '🌙';
    if (label) label.textContent = isDark ? 'Light' : 'Dark';

    localStorage.setItem('darkMode', isDark ? 'enabled' : 'disabled');
}

// Load dark mode preference on page load
function loadDarkModePreference() {
    if (localStorage.getItem('darkMode') === 'enabled') {
        document.body.classList.add('dark-mode');

        const icon = document.getElementById('darkModeIcon');
        const label = document.getElementById('darkModeLabel');

        if (icon) icon.textContent = '☀️';
        if (label) label.textContent = 'Light';
    }
}

// ==========================================
// Modal Management
// ==========================================

// Global logsData will be set by each page
window.logsData = window.logsData || [];

function openModal(index) {
    const log = window.logsData[index];
    if (!log) return;

    const modal = document.getElementById('detailModal');
    const modalTitle = document.getElementById('modalTitle');
    const modalBody = document.getElementById('modalBody');

    if (!modal || !modalTitle || !modalBody) return;

    // Set title
    modalTitle.textContent = `#${log.log_number} - ${log.title}`;

    // Parse and render markdown
    const content = log.full_content || '';
    const html = marked.parse(content);

    // Safe rendering: trusted local dev-log content only
    // Content source: local markdown files generated by dev-log.sh
    const tempDiv = document.createElement('div');
    tempDiv.innerHTML = html;
    modalBody.textContent = '';
    modalBody.appendChild(tempDiv);

    modal.style.display = 'flex';
    document.body.style.overflow = 'hidden';
}

function closeModal(event) {
    if (event && event.target.classList.contains('modal-content')) {
        return;
    }

    const modal = document.getElementById('detailModal');
    if (!modal) return;

    modal.style.display = 'none';
    document.body.style.overflow = 'auto';
}

// Close modal on ESC key
document.addEventListener('keydown', function(event) {
    if (event.key === 'Escape') {
        closeModal();
    }
});

// ==========================================
// Marked.js Configuration
// ==========================================

if (typeof marked !== 'undefined') {
    marked.setOptions({
        breaks: true,
        gfm: true,
        headerIds: false,
        mangle: false
    });
}

// ==========================================
// Initialize on page load
// ==========================================

document.addEventListener('DOMContentLoaded', function() {
    loadDarkModePreference();
});
